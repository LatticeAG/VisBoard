import type { ChecklistItem, FileRecord, ProjectStatus } from "@visboard/shared";
import { AGENTS_MD_MARKER } from "./templates.js";

export interface AgentsMdParticipantUser {
  id: string;
  display_name: string;
}

export interface AgentsMdParticipantAgent {
  id: string;
  name: string;
  scopes: string[];
}

export interface AgentsMdNote {
  slug: string;
  title: string;
  body: string;
}

export interface AgentsMdChecklistItem {
  id: string;
  text: string;
  done: boolean;
  assignee_type?: "user" | "agent" | null;
  assignee_id?: string | null;
}

export interface AgentsMdChecklist {
  id: string;
  title: string;
  items: AgentsMdChecklistItem[];
}

export interface AgentsMdFile {
  id: string;
  name: string;
  mime_type: string;
  size_bytes: number;
}

export interface GenerateAgentsMdInput {
  project: {
    name: string;
    description?: string;
    status: ProjectStatus;
    slug: string;
  };
  workspace: {
    slug: string;
  };
  apiBaseUrl: string;
  users: AgentsMdParticipantUser[];
  agents: AgentsMdParticipantAgent[];
  notes: AgentsMdNote[];
  checklists: AgentsMdChecklist[];
  files: AgentsMdFile[];
  localOverrides?: string | null;
}

function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function summarizeNote(body: string): string {
  const lines = body
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));

  const first = lines[0] ?? "";
  if (first.length <= 80) return first || "-";
  return `${first.slice(0, 77)}...`;
}

function formatAssignee(item: AgentsMdChecklistItem): string {
  if (!item.assignee_type || !item.assignee_id) return "";
  return ` @${item.assignee_type}:${item.assignee_id}`;
}

function formatChecklistItem(item: AgentsMdChecklistItem): string {
  const checkbox = item.done ? "[x]" : "[ ]";
  return `- ${checkbox} ${item.text} (\`${item.id}\`)${formatAssignee(item)}`;
}

function renderParticipants(
  users: AgentsMdParticipantUser[],
  agents: AgentsMdParticipantAgent[],
): string {
  const humanLines =
    users.length > 0
      ? users.map((u) => `- ${u.display_name} (\`${u.id}\`)`).join("\n")
      : "- _None._";

  const agentLines =
    agents.length > 0
      ? agents.map((a) => `- ${a.name} (\`${a.id}\`) scopes: ${a.scopes.join(", ")}`).join("\n")
      : "- _None._";

  return `## Participants
### Humans
${humanLines}

### Agents
${agentLines}`;
}

function renderNotes(notes: AgentsMdNote[]): string {
  const filtered = notes.filter((n) => n.slug !== "agents.local.md" && n.slug !== "agents.md");

  if (filtered.length === 0) {
    return "## Notes\n_No notes yet._";
  }

  const rows = filtered
    .map((n) => `| ${n.slug} | ${n.title} | ${summarizeNote(n.body)} |`)
    .join("\n");

  return `## Notes
| Slug | Title | Summary |
|------|-------|---------|
${rows}`;
}

function renderChecklists(checklists: AgentsMdChecklist[]): string {
  if (checklists.length === 0) {
    return "## Checklists\n_None._";
  }

  return checklists
    .map((chk) => {
      const items =
        chk.items.length > 0
          ? chk.items.map((item) => formatChecklistItem(item)).join("\n")
          : "- _No items._";
      return `### ${chk.title} (\`${chk.id}\`)\n${items}`;
    })
    .join("\n\n");
}

function renderFiles(files: AgentsMdFile[]): string {
  if (files.length === 0) {
    return "## Files\n| ID | Name | Type | Size |\n|----|------|------|------|\n| _None._ | | | |";
  }

  const rows = files
    .map((f) => `| \`${f.id}\` | ${f.name} | ${f.mime_type} | ${formatBytes(f.size_bytes)} |`)
    .join("\n");

  return `## Files
| ID | Name | Type | Size |
|----|------|------|------|
${rows}`;
}

export function generate(input: GenerateAgentsMdInput): string {
  const {
    project,
    workspace,
    apiBaseUrl,
    users,
    agents,
    notes,
    checklists,
    files,
    localOverrides,
  } = input;

  const description = project.description?.trim() || "No description set.";
  const contextPath = `/v1/workspaces/${workspace.slug}/projects/${project.slug}/context?include=headings`;

  const sections = [
    AGENTS_MD_MARKER,
    `# AGENTS.md: ${project.name}`,
    "",
    "> Generated by VisBoard. Do not edit this file directly.",
    "> Human overrides: create note `agents.local.md` (appended below).",
    "",
    "## Purpose",
    description,
    "",
    "## Status",
    project.status,
    "",
    "## API",
    `- Base URL: ${apiBaseUrl}/v1`,
    `- Workspace: \`${workspace.slug}\``,
    `- Project: \`${project.slug}\``,
    `- Context endpoint: \`GET ${contextPath}\``,
    "- Recommended scopes: `read`, `write:checklists`, `write:events`",
    "",
    renderParticipants(users, agents),
    "",
    renderNotes(notes),
    "",
    "## Checklists",
    renderChecklists(checklists),
    "",
    renderFiles(files),
    "",
    "## Local overrides",
    localOverrides?.trim() || "_None._",
    "",
  ];

  return sections.join("\n");
}

/** Convenience adapters for shared types */
export function toAgentsMdChecklistItem(item: ChecklistItem): AgentsMdChecklistItem {
  return {
    id: item.id,
    text: item.text,
    done: item.done,
    assignee_type: item.assignee_type ?? null,
    assignee_id: item.assignee_id ?? null,
  };
}

export function toAgentsMdFile(file: FileRecord): AgentsMdFile {
  return {
    id: file.id,
    name: file.name,
    mime_type: file.mime_type,
    size_bytes: file.size_bytes,
  };
}
